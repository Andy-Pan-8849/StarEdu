"""Check a model-written SQL statement before it goes anywhere near the database.

An allow-list, not a block-list: one SELECT, reading only the views in `ai_sql`, calling only
the functions below. The statement that is run is the one the parser regenerates, not the text
the model wrote, so what was checked is what executes.

This is the second layer. The first is the database: the statement runs as a role that can only
read the views, and the views only return rows the caller may see.
"""

from dataclasses import dataclass

import sqlglot
from sqlglot import exp
from sqlglot.errors import SqlglotError

from starit_core.auth import Identity
from starit_core.dataaccess.schema import CAMPUSES, VIEW_ROLES, can_use_view
from starit_core.permissions import COMPANY_WIDE_ROLES

MAX_SQL_CHARS = 4000

# Names as the parser reports them, which are not always the SQL spelling (string_agg is
# "group_concat", date_trunc is "timestamp_trunc", to_char is "time_to_str").
ALLOWED_FUNCTIONS = frozenset(
    {
        "count", "sum", "avg", "min", "max", "round", "coalesce", "nullif", "lower", "upper",
        "length", "concat", "abs", "ceil", "floor", "greatest", "least", "cast", "case", "if",
        "exists", "extract", "current_date", "current_timestamp", "timestamp_trunc",
        "date_trunc", "group_concat", "time_to_str", "left", "right", "replace", "trim",
        "format", "substring", "mod", "pow", "sqrt", "div",
    }
)  # fmt: skip

# Anything of these kinds, anywhere in the statement (including inside a WITH), is refused.
FORBIDDEN_NODES: tuple[type[exp.Expression], ...] = (
    exp.Insert, exp.Update, exp.Delete, exp.Merge, exp.Create, exp.Drop, exp.Alter, exp.Command,
    exp.Into, exp.Lock, exp.Set, exp.TruncateTable, exp.Copy, exp.Grant, exp.Use,
)  # fmt: skip


class SqlRejected(Exception):
    """The statement is not acceptable. The message can be shown to the model so it can fix it."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


class AccessDenied(Exception):
    """The statement is fine SQL but asks for data this person has no access to."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


@dataclass(frozen=True)
class ValidatedSql:
    sql: str  # regenerated by the parser: this is what runs
    views: tuple[str, ...]


def validate_sql(sql: str, identity: Identity | None = None) -> ValidatedSql:
    text = sql.strip().rstrip(";").strip()
    if not text:
        raise SqlRejected("empty", "The statement is empty.")
    if len(text) > MAX_SQL_CHARS:
        raise SqlRejected("too_long", f"The statement is longer than {MAX_SQL_CHARS} characters.")
    try:
        statements = sqlglot.parse(text, read="postgres")
    except SqlglotError as exc:
        raise SqlRejected("syntax", f"The statement does not parse: {str(exc)[:200]}") from exc
    if len(statements) != 1 or statements[0] is None:
        raise SqlRejected("multiple_statements", "Write exactly one statement.")
    root = statements[0]
    if not isinstance(root, exp.Select | exp.Union):
        raise SqlRejected("not_select", "Only a SELECT statement is allowed.")

    for node in root.walk():
        if isinstance(node, FORBIDDEN_NODES):
            raise SqlRejected(
                "forbidden_construct", f"{type(node).__name__} is not allowed; only reading."
            )

    views = _check_tables(root)
    _check_functions(root)
    if identity is not None:
        _check_access(views, root, identity)
    return ValidatedSql(
        sql=root.sql(dialect="postgres", comments=False), views=tuple(sorted(views))
    )


def _check_tables(root: exp.Expression) -> set[str]:
    ctes = {cte.alias.lower() for cte in root.find_all(exp.CTE)}
    views: set[str] = set()
    for table in root.find_all(exp.Table):
        if not isinstance(table.this, exp.Identifier):
            raise SqlRejected("table_function", "Table functions are not allowed.")
        name, schema = table.name.lower(), table.db.lower()
        if not schema and name in ctes:
            continue
        if not schema:
            raise SqlRejected(
                "unqualified_table",
                f"Write {name!r} as ai_sql.{name}; only the views in ai_sql can be read.",
            )
        if table.catalog or schema != "ai_sql" or name not in VIEW_ROLES:
            raise SqlRejected(
                "table_not_allowed",
                f"{schema}.{name} cannot be read. The views are: "
                + ", ".join(f"ai_sql.{v}" for v in sorted(VIEW_ROLES))
                + ".",
            )
        views.add(name)
    return views


def _check_functions(root: exp.Expression) -> None:
    for node in root.walk():
        if not isinstance(node, exp.Func) or isinstance(node, exp.Connector):
            continue
        name = (node.name if isinstance(node, exp.Anonymous) else node.sql_name()).lower()
        if name not in ALLOWED_FUNCTIONS:
            raise SqlRejected("function_not_allowed", f"The function {name}() is not allowed.")


def _check_access(views: set[str], root: exp.Expression, identity: Identity) -> None:
    for view in sorted(views):
        if not can_use_view(identity.roles, view):
            raise AccessDenied("restricted_view", f"No access to {view}.")
    if identity.roles & COMPANY_WIDE_ROLES:
        return
    own = (identity.campus_id or "").upper()
    found = _campus_literals(root)
    if "campuses" in views:
        found += _campus_name_literals(root)
    for campus in found:
        if campus != own:
            raise AccessDenied(
                "campus_scope",
                f"The question is about campus {campus}, outside this person's scope.",
            )


def _campus_literals(root: exp.Expression) -> list[str]:
    """Campus codes written into the statement as `campus_id = 'XX'` or `campus_id IN (...)`."""
    found: list[str] = []
    for node in root.walk():
        if isinstance(node, exp.EQ):
            pairs = [(node.this, node.expression), (node.expression, node.this)]
            for column, value in pairs:
                if _is_campus_column(column) and isinstance(value, exp.Literal) and value.is_string:
                    found.append(value.name.upper())
        elif isinstance(node, exp.In) and _is_campus_column(node.this):
            found += [
                v.name.upper()
                for v in node.expressions
                if isinstance(v, exp.Literal) and v.is_string
            ]
    return found


def _campus_name_literals(root: exp.Expression) -> list[str]:
    """Campus codes for city names written into a statement that reads the campuses view
    (`WHERE name = 'Beijing'`, `ILIKE '%shanghai%'`). Only there: a hotel claim's `city` is a
    travel destination, not the person's campus."""
    names = {name.split(" (")[0].lower(): code for code, name in CAMPUSES.items()}
    found = []
    for node in root.walk():
        if isinstance(node, exp.Literal) and node.is_string:
            text = node.name.lower()
            found += [code for name, code in names.items() if name in text]
    return found


def _is_campus_column(node: exp.Expression | None) -> bool:
    return isinstance(node, exp.Column) and node.name.lower() == "campus_id"
